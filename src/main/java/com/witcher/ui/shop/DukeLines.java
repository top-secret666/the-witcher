package main.java.com.witcher.ui.shop;

import java.util.concurrent.ThreadLocalRandom;

/**
 * Реплики герцога в духе торговца из Resident Evil Village — вежливо, театрально, с намёком.
 */
public final class DukeLines {

    private DukeLines() {
    }

    public static final String WELCOME = """
            Я вас ждал, господин из Ривии.
            О вас слышали и ведьмаки, и купцы — герой, что ищет дорогу дальше.
            Простите манеры: зовите меня Герцог. Я — скромный торговец.
            Броня, зелья, клинки — чего пожелаете, то и найдёте.""";

    public static final String IDLE = "Не стесняйтесь. Если просто смотрите — смотрите сколько угодно.";

    public static String forCategory(ShopCategory category) {
        return switch (category) {
            case CHEST -> pick(
                "Кирасы — дело серьёзное. Торс цел — и охота идёт легче.",
                "Да, да… тот самый раздел. Защита сердца дороже золота, не правда ли?",
                "Вижу, взгляд цепляется за нагрудники. Мудро.");
            case LEGS -> pick(
                "Штаны крепкие — ноги целее, тропа короче.",
                "Низ доспеха не менее важен. Поверьте скромному торговцу.",
                "Отличный выбор раздела. По болотам ходить придётся немало.");
            case GLOVES -> pick(
                "Перчатки… Мелочь, скажете вы. А хват клинка — нет.",
                "Рукам тепло, клинку — верно. Берите, не пожалеете.",
                "Ловкость стоит каждой кроны. Особенно когда когти близко.");
            case BOOTS -> pick(
                "Сапоги — верные спутники. И по грязи, и от удара.",
                "Хорошая подошва спасает не реже стали.",
                "В этих краях без сапог далеко не уйдёшь, господин ведьмак.");
            case POTION -> pick(
                "Зелья, отвары… Пахнет риском. Мне нравится.",
                "Алхимия — это тоже инвестиция, господин из Ривии.",
                "Осторожнее с дозой. Я продаю — вы отвечаете за последствия.");
            case SETS -> pick(
                "Целые комплекты! Школьные доспехи — для тех, кто знает толк.",
                "Ах, охотник на полный набор… У меня есть кое-что особенное.",
                "Четыре части, один замысел. Так рождаются легенды.");
            case WEAPON -> pick(
                "Сталь режет, серебро жжёт. Выбирайте по вкусу.",
                "Оружие — не игрушка. Но и без него в эти земли не ходят.",
                "Клинок верный важнее клинка яркого. Ха-ха… шутка. Берите оба.");
        };
    }

    public static String statGlyphsLegend() {
        return "У цифр в списке значки: щит — защита, молния — выносливость, ромб — знаки. Плюс — лучше, минус — хуже.";
    }

    public static String rowInspect(String itemName, int price) {
        return pick(
            "Так-так… " + itemName + ". За " + price + " крон — сделка честная.",
            "Вижу, вы присматривались к этому. " + itemName + ", " + price + " крон.",
            "Ага! " + itemName + ". С таким вы точно ничего не упустите.",
            "Интересный выбор. " + itemName + " — " + price + " крон, не больше."
        );
    }

    public static String purchaseOk(String itemName, int price) {
        return pick(
            "Благодарю за покупку. С этим вы не пропустите ничего важного.",
            "Превосходный выбор! " + itemName + " — " + price + " крон. Доволен?",
            "Поздравляю. Маленькими шагами кошелёк полнеет, а вы — крепчаете.",
            "Отлично! Жду, когда испытаете это в деле.",
            "Сделка заключена. Приходите ещё — ассортимент живой."
        );
    }

    public static String purchaseFailMoney() {
        return pick(
            "Ах… если бы у вас хватало средств. Покупатель всегда прав — но кошелёк молчит.",
            "Недостаточно крон, господин из Ривии. Даже скромному торговцу нужна плата.",
            "Хм. Запас прочности кошелька исчерпан. Может, что-то скромнее?",
            "За такую цену — да. За ваш остаток — увы, нет."
        );
    }

    public static String purchaseFailSold() {
        return pick(
            "Увы, уже продано. В моей лавке товары не вечны.",
            "Опоздали, господин ведьмак. Другой успел раньше.",
            "Этого на полке больше нет. Загляните позже — вдруг повезёт."
        );
    }

    public static String purchaseFailGeneric() {
        return pick(
            "Что-что? Не расслышал…",
            "Простите, повторите. Шум за стенами…",
            "Хм? Нет, так не пойдёт."
        );
    }

    public static String walletReveal() {
        return pick(
            "Стойте. Вот плата за Арнскрон — четыреста двадцать крон. Не промотайте в первый же день.",
            "Прежде чем торговаться — ваш мешок. Считайте сами: четыреста двадцать.",
            "Ах да, чуть не забыл. Ваш гонорар. Четыреста двадцать крон — и ни одной лишней."
        );
    }

    public static String walletRevealAfter() {
        return pick(
            "Вот и вся сумма. Не думайте, что кошелёк бездонный — каждая крона на счету.",
            "Четыреста двадцать. Фиксированная плата. Теперь вы знаете, с чем имеете дело.",
            "Теперь, когда мы прояснили финансы — выбирайте с умом, господин из Ривии."
        );
    }

    private static String pick(String... lines) {
        return lines[ThreadLocalRandom.current().nextInt(lines.length)];
    }
}
